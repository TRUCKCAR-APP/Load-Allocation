CREATE TABLE IF NOT EXISTS freight_loads (
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    generator_company_id         VARCHAR(255)   NOT NULL,
    generator_company_name       VARCHAR(255)   NOT NULL,
    cargo_description            VARCHAR(255)   NOT NULL,
    weight_tons                  DOUBLE PRECISION NOT NULL,
    volume_m3                    DOUBLE PRECISION,
    required_truck_type          VARCHAR(255)   NOT NULL,
    origin_city                  VARCHAR(255)   NOT NULL,
    origin_department            VARCHAR(255)   NOT NULL,
    origin_latitude              DOUBLE PRECISION NOT NULL,
    origin_longitude             DOUBLE PRECISION NOT NULL,
    destination_city             VARCHAR(255)   NOT NULL,
    destination_department       VARCHAR(255)   NOT NULL,
    destination_latitude         DOUBLE PRECISION NOT NULL,
    destination_longitude        DOUBLE PRECISION NOT NULL,
    offered_budget               NUMERIC(38, 2) NOT NULL,
    status                       VARCHAR(255)   NOT NULL,
    published_at                 TIMESTAMP(6)   NOT NULL,
    correlation_id               UUID,
    assigned_driver_id           VARCHAR(255),
    assigned_driver_name         VARCHAR(255),
    assigned_vehicle_plate       VARCHAR(255),
    assigned_at                  TIMESTAMP(6),
    assignment_status            VARCHAR(255),
    assignment_status_changed_at TIMESTAMP(6),
    assignment_attempts          INTEGER        NOT NULL DEFAULT 0,
    trip_started_at              TIMESTAMP(6),
    delivered_at                 TIMESTAMP(6),
    pod_receiver_name            VARCHAR(150),
    pod_receiver_document        VARCHAR(40),
    pod_notes                    VARCHAR(500),
    pod_has_signature            BOOLEAN,
    pod_has_photo                BOOLEAN,
    cancellation_reason          VARCHAR(500),
    cancelled_at                 TIMESTAMP(6),
    cancelled_by                 VARCHAR(255),
    version                      BIGINT DEFAULT 0,
    CONSTRAINT freight_loads_status_check CHECK (status IN
        ('AVAILABLE', 'ASSIGNED', 'IN_TRANSIT', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT freight_loads_assignment_status_check CHECK (assignment_status IN
        ('PROPOSED', 'NOTIFIED', 'ACCEPTED', 'REJECTED', 'TIMEOUT', 'UNASSIGNED_NO_DRIVERS')),
    CONSTRAINT freight_loads_required_truck_type_check CHECK (required_truck_type IN
        ('TURBO', 'SENCILLO', 'DOBLETROQUE', 'CUATRO_MANOS', 'MINIMULA', 'TRACTOMULA_3S3', 'REFRIGERADO'))
);

CREATE INDEX IF NOT EXISTS idx_load_status ON freight_loads (status);
CREATE INDEX IF NOT EXISTS idx_generator_id ON freight_loads (generator_company_id);

CREATE TABLE IF NOT EXISTS freight_load_discarded_drivers (
    load_id   BIGINT       NOT NULL REFERENCES freight_loads (id),
    driver_id VARCHAR(255) NOT NULL,
    PRIMARY KEY (load_id, driver_id)
);

-- Columnas de data URL de la versión anterior: V3 traslada su contenido al almacenamiento de objetos y las elimina.
CREATE TABLE IF NOT EXISTS freight_load_pod_media (
    load_id            BIGINT       PRIMARY KEY,
    signature_data_url TEXT,
    photo_url          TEXT,
    created_at         TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS load_allocation_outbox_events (
    id             UUID PRIMARY KEY,
    aggregate_type VARCHAR(100)   NOT NULL,
    aggregate_id   VARCHAR(100)   NOT NULL,
    event_type     VARCHAR(150)   NOT NULL,
    payload        TEXT           NOT NULL,
    occurred_at    TIMESTAMPTZ(6) NOT NULL,
    created_at     TIMESTAMPTZ(6) NOT NULL,
    published_at   TIMESTAMPTZ(6),
    attempts       INTEGER        NOT NULL,
    last_error     VARCHAR(2000)
);

CREATE INDEX IF NOT EXISTS idx_load_outbox_unpublished ON load_allocation_outbox_events (published_at, created_at);
